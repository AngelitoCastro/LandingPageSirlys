/* LocalStorage key for the persisted language preference */
export const STORAGE_KEY = 'sirlys_lang';

/* ---- State ---- */
let currentLang = localStorage.getItem(STORAGE_KEY) || 'es';
const subscribers = [];

/* ---- Subscribe to language changes (for re-renders) ---- */
export const onLanguageChange = (fn) => subscribers.push(fn);

export const getCurrentLang = () => currentLang;

/* ---- Translate all [data-translate] elements in the DOM ---- */
export const translateDOM = (lang) => {
    const dict = translations[lang];
    document.querySelectorAll('[data-translate]').forEach((el) => {
        const key = el.getAttribute('data-translate');
        if (dict && dict[key]) {
            if (el.tagName === 'INPUT' || el.tagName === 'TEXTAREA') {
                el.placeholder = dict[key];
            } else if (el.tagName === 'OPTION') {
                el.textContent = dict[key];
            } else {
                el.textContent = dict[key];
            }
        }
    });
    document.documentElement.setAttribute('lang', lang);
};

/* ---- Set the active language, re-translate and notify ---- */
export const setLanguage = (lang) => {
    if (!translations[lang]) return;
    currentLang = lang;

    document.querySelectorAll('.lang-btn').forEach((btn) => {
        const isActive = btn.getAttribute('data-lang') === lang;
        btn.classList.toggle('active', isActive);
        btn.setAttribute('aria-pressed', String(isActive));
    });

    translateDOM(lang);
    localStorage.setItem(STORAGE_KEY, lang);
    subscribers.forEach((fn) => fn(lang));
};

/* ---- Wire up language toggle buttons ---- */
export const initLanguageSelector = () => {
    document.querySelectorAll('.lang-btn').forEach((btn) => {
        btn.addEventListener('click', () => setLanguage(btn.getAttribute('data-lang')));
    });
};